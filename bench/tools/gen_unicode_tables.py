"""Generate engine/rust/unicode_tables.rs: exact \\p{L} (letters) and \\p{N} (numbers) code-point ranges.
Rust's std has no general categories; char::is_alphabetic() also counts combining marks (e.g. Devanagari vowel
signs), which would break CLIP tokenization of Indic text. Source: Python's unicodedata (str.isalpha == \\p{L}).
  python gen_unicode_tables.py
"""
import os, sys, unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(sys.maxunicode + 1):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False
        else:
            ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        if not ok and start is not None:
            out.append((start, cp - 1)); start = None
    if start is not None:
        out.append((start, sys.maxunicode))
    return out


letters = ranges(lambda c: c.isalpha())
numbers = ranges(lambda c: unicodedata.category(c) in ("Nd", "Nl", "No"))
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engine", "rust", "unicode_tables.rs")
with open(path, "w", encoding="utf-8", newline="\n") as f:
    f.write(f"//! Generated by bench/tools/gen_unicode_tables.py from Unicode {unicodedata.unidata_version}. Do not edit.\n")
    f.write("#![forbid(unsafe_code)]\n\n")
    for name, rs in (("LETTERS", letters), ("NUMBERS", numbers)):
        f.write(f"pub const {name}: [(u32, u32); {len(rs)}] = [\n")
        for i in range(0, len(rs), 6):
            f.write("    " + " ".join(f"(0x{a:X}, 0x{b:X})," for a, b in rs[i:i + 6]) + "\n")
        f.write("];\n\n")
    f.write("fn in_table(t: &[(u32, u32)], c: char) -> bool {\n"
            "    let c = c as u32;\n"
            "    t.binary_search_by(|&(a, b)| if c < a { std::cmp::Ordering::Greater } else if c > b { std::cmp::Ordering::Less } else { std::cmp::Ordering::Equal }).is_ok()\n"
            "}\n\n"
            "/// Unicode general category L* (\\p{L}).\npub fn is_letter(c: char) -> bool { in_table(&LETTERS, c) }\n"
            "/// Unicode general category N* (\\p{N}).\npub fn is_number(c: char) -> bool { in_table(&NUMBERS, c) }\n")
print(f"wrote {path}: {len(letters)} letter ranges, {len(numbers)} number ranges (Unicode {unicodedata.unidata_version})")
